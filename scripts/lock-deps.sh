#!/usr/bin/env bash
# T1.3 Regenerate dependency lock files (Linux/macOS).
#
# Cross-platform locks (requirements.txt / requirements-dev.txt) are generated
# with:
#   uv pip compile --universal --python-version 3.10 <in> -o <out>
#
# pip-tools' pip-compile has NO --universal option (verified on pip-tools 7.6.2)
# and would write a platform-only lock that loses the sys_platform markers, so
# this script REFUSES to run without uv instead of overwriting committed locks.
#
# Safety: each lock is generated to a temp file, the uv header and the required
# sys_platform markers are validated, and only then is the committed file
# replaced. A failed or interrupted run leaves the existing lock files untouched
# and removes its temp files (also covered by .gitignore: requirements*.txt.tmp*).
#
# Usage: bash scripts/lock-deps.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

log() { printf '[lock-deps] %s\n' "$*"; }
fail() { printf '[lock-deps][ERROR] %s\n' "$*" >&2; exit 1; }

STALE_TEMPS=(
    requirements.txt.tmp
    requirements.txt.tmp.hdr
    requirements-dev.txt.tmp
    requirements-dev.txt.tmp.hdr
)
TMP_FILES=()

cleanup() {
    local path
    for path in "${TMP_FILES[@]:-}"; do
        [ -n "$path" ] || continue
        rm -f "$path" 2>/dev/null || true
    done
    TMP_FILES=()
}
trap cleanup EXIT INT TERM

remove_stale_temps() {
    local path
    for path in "${STALE_TEMPS[@]}"; do
        rm -f "$path" 2>/dev/null || true
    done
}

[ -f requirements.in ] || fail "requirements.in not found (run from the project root)."
[ -f requirements-dev.in ] || fail "requirements-dev.in not found (run from the project root)."

remove_stale_temps

if ! command -v uv >/dev/null 2>&1; then
    fail "uv not found. Cross-platform lock generation requires uv:
    uv pip compile --universal --python-version 3.10 ...
pip-tools pip-compile has no --universal option and would write a platform-only
lock (losing sys_platform markers), so this script refuses to run.
Install uv first, e.g.: pip install uv   (https://docs.astral.sh/uv/)"
fi

new_lock() {
    local in_file="$1"
    local out_file="$2"
    local tmp_file="$3"
    local fixed_file="${tmp_file}.hdr"
    TMP_FILES+=("$tmp_file" "$fixed_file")
    rm -f "$tmp_file"
    log "Compiling $in_file -> $out_file (universal, Python 3.10)"
    if ! uv pip compile --universal --python-version 3.10 "$in_file" -o "$tmp_file"; then
        fail "uv pip compile failed for $in_file; $out_file left untouched."
    fi
    if [ ! -s "$tmp_file" ]; then
        fail "uv pip compile produced no output for $in_file."
    fi
    # uv records the -o argument in the header; rewrite it to the final name so the
    # committed lock is identical to a direct "uv pip compile ... -o <out>" run.
    {
        printf '# This file was autogenerated by uv via the following command:\n'
        printf '#    uv pip compile --universal --python-version 3.10 %s -o %s\n' "$in_file" "$out_file"
        tail -n +3 "$tmp_file"
    } > "$fixed_file"
    mv -f "$fixed_file" "$tmp_file"
    if ! grep -qF '# This file was autogenerated by uv' "$tmp_file"; then
        fail "Generated file is not a uv lock; $out_file left untouched."
    fi
    if ! grep -qF "sys_platform == 'win32'" "$tmp_file"; then
        fail "Generated lock is missing marker [sys_platform == 'win32']; $out_file left untouched."
    fi
    if ! grep -qF "sys_platform != 'darwin'" "$tmp_file"; then
        fail "Generated lock is missing marker [sys_platform != 'darwin']; $out_file left untouched."
    fi
    mv -f "$tmp_file" "$out_file"
    log "  OK: $out_file (markers verified)"
}

new_lock requirements.in requirements.txt requirements.txt.tmp
new_lock requirements-dev.in requirements-dev.txt requirements-dev.txt.tmp

log 'Done. Review "git diff" before committing the lock files.'
