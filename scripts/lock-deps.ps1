<#
.SYNOPSIS
    Regenerate the dependency lock files (T1.3).

.DESCRIPTION
    Produces requirements.txt and requirements-dev.txt as cross-platform locks
    (platform markers such as sys_platform == 'win32' are preserved).

    Lock generation REQUIRES uv:
        uv pip compile --universal --python-version 3.10 <in> -o <out>

    pip-tools' pip-compile has NO cross-platform "--universal" option (verified on
    pip-tools 7.6.2). If uv is missing this script REFUSES to run instead of
    silently overwriting the committed cross-platform locks with a platform-only
    lock that would lose the sys_platform markers.

    Safety: each lock is generated to a temp file, the uv header and the required
    sys_platform markers are validated, and only then is the committed file
    replaced. A failed run leaves the existing lock files untouched.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File scripts\lock-deps.ps1
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
Set-Location $Root

function Log([string]$Text) { Write-Host "[lock-deps] $Text" -ForegroundColor Cyan }
function Fail([string]$Text) { Write-Host "[lock-deps][ERROR] $Text" -ForegroundColor Red; exit 1 }

if (-not (Test-Path 'requirements.in')) { Fail 'requirements.in not found (run from the project root).' }
if (-not (Test-Path 'requirements-dev.in')) { Fail 'requirements-dev.in not found (run from the project root).' }

$uv = Get-Command uv -ErrorAction SilentlyContinue
if (-not $uv) {
    Fail @'
uv not found. Cross-platform lock generation requires uv:
    uv pip compile --universal --python-version 3.10 ...
pip-tools pip-compile has no --universal option and would write a platform-only
lock (losing sys_platform markers), so this script refuses to run.
Install uv first, e.g.:  py -3.10 -m pip install uv   (https://docs.astral.sh/uv/)
'@
}
Log "uv: $($uv.Source)"

$requiredMarkers = @(
    "sys_platform == 'win32'",
    "sys_platform != 'darwin'"
)

function New-Lock([string]$InFile, [string]$OutFile) {
    $tempFile = "$OutFile.tmp"
    if (Test-Path $tempFile) { Remove-Item -Force $tempFile }
    Log "Compiling $InFile -> $OutFile (universal, Python 3.10)"
    & $uv.Source pip compile --universal --python-version 3.10 $InFile -o $tempFile
    if ($LASTEXITCODE -ne 0) {
        Remove-Item -Force $tempFile -ErrorAction SilentlyContinue
        Fail "uv pip compile failed for $InFile (exit $LASTEXITCODE); $OutFile left untouched."
    }
    if (-not (Test-Path $tempFile)) { Fail "uv pip compile produced no output for $InFile." }
    # uv records the -o argument in the header; rewrite it to the final name so the
    # committed lock is identical to a direct "uv pip compile ... -o <out>" run.
    $allLines = Get-Content -Encoding UTF8 $tempFile
    $header = @(
        '# This file was autogenerated by uv via the following command:',
        "#    uv pip compile --universal --python-version 3.10 $InFile -o $OutFile"
    )
    $bodyLines = @()
    if ($allLines.Count -gt 2) { $bodyLines = $allLines[2..($allLines.Count - 1)] }
    $rewritten = (($header + $bodyLines) -join "`n") + "`n"
    [IO.File]::WriteAllText($tempFile, $rewritten, (New-Object System.Text.UTF8Encoding($false)))

    $text = Get-Content -Raw -Encoding UTF8 $tempFile
    if (-not $text.Contains('# This file was autogenerated by uv')) {
        Remove-Item -Force $tempFile -ErrorAction SilentlyContinue
        Fail "Generated file does not look like a uv lock; $OutFile left untouched."
    }
    foreach ($marker in $requiredMarkers) {
        if (-not $text.Contains($marker)) {
            Remove-Item -Force $tempFile -ErrorAction SilentlyContinue
            Fail "Generated lock is missing marker [$marker]; $OutFile left untouched."
        }
    }
    Move-Item -Force $tempFile $OutFile
    Log "  OK: $OutFile (markers verified)"
}

New-Lock 'requirements.in' 'requirements.txt'
New-Lock 'requirements-dev.in' 'requirements-dev.txt'

Log 'Done. Review "git diff" before committing the lock files.'
exit 0
